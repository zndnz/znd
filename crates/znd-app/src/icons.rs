/// `rect` の中央に、一辺 `size` px で描く。
pub(crate) fn paint_sized(p: &Painter, rect: Rect, icon: Icon, color: Color32, size: f32) {
    if icon == Icon::Fx {
        p.text(rect.center(), Align2::CENTER_CENTER, "fx", FontId::proportional(size * 0.72), color);
        return;
    }
    let s = size / 16.0;
    let origin = rect.center() - vec2(size, size) * 0.5;
    // 整列アイコンは左揃えの絵を反転・転置して使い回す
    let (flip, transpose) = match icon {
        Icon::AlignRight => (true, false),
        Icon::AlignTop | Icon::AlignVCenter => (false, true),
        Icon::AlignBottom => (true, true),
        _ => (false, false),
    };
    let pt = |&(x, y): &(f32, f32)| -> Pos2 {
        let x = if flip { 16.0 - x } else { x };
        let (x, y) = if transpose { (y, x) } else { (x, y) };
        pos2(origin.x + x * s, origin.y + y * s)
    };
    let stroke = Stroke::new(1.3_f32, color);
    for prim in prims(icon) {
        match prim {
            L(pts) => {
                p.add(Shape::line(pts.iter().map(pt).collect(), stroke));
            }
            C(pts) => {
                p.add(Shape::closed_line(pts.iter().map(pt).collect(), stroke));
            }
            F(pts) => {
                p.add(Shape::convex_polygon(pts.iter().map(pt).collect(), color, Stroke::NONE));
            }
            O(x, y, r) => {
                p.circle_stroke(pt(&(*x, *y)), r * s, stroke);
            }
            D(x, y, r) => {
                p.circle_filled(pt(&(*x, *y)), r * s, color);
            }
            A(x, y, r, a0, a1) => {
                let n = (((a1 - a0).abs() / 20.0).ceil() as usize).max(2);
                let pts = (0..=n)
                    .map(|i| {
                        let a = (a0 + (a1 - a0) * i as f32 / n as f32).to_radians();
                        pt(&(x + r * a.cos(), y + r * a.sin()))
                    })
                    .collect();
                p.add(Shape::line(pts, stroke));
            }
        }
    }
}

pub(crate) fn paint(p: &Painter, rect: Rect, icon: Icon, color: Color32) {
    paint_sized(p, rect, icon, color, 15.0);
}
