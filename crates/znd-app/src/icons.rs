type Pts = &'static [(f32, f32)];

enum P {
    /// 折れ線。
    L(Pts),
    /// 閉じた線。
    C(Pts),
    /// 塗りつぶした凸多角形。
    F(Pts),
    /// 円（中心 x, y, 半径）。
    O(f32, f32, f32),
    /// 塗りつぶした円。
    D(f32, f32, f32),
    /// 円弧（中心 x, y, 半径, 開始角, 終了角。度、時計回り）。
    A(f32, f32, f32, f32, f32),
}
