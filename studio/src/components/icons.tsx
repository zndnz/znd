export function Icon({ name, size = 16, className, filled }: { name: string; size?: number; className?: string; filled?: boolean }) {
  const C = icons[name] ?? Ellipsis;
  return <C size={size} className={className} fill={filled ? "currentColor" : "none"} strokeWidth={1.75} aria-hidden />;
}
